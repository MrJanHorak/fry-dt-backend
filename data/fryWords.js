export const ALL_FRY_WORDS = FRY_LISTS.flatMap((l) => l.words)

const RANK = new Map(ALL_FRY_WORDS.map((word, i) => [word.toLowerCase(), i + 1]))

/** 1-based rank of a word in the Fry 1,000 (case-insensitive), or null. */
export const getFryRank = (word) =>
  RANK.get(String(word || '').trim().toLowerCase()) || null

/** Fry list number (1–10) for a word, or null if it is not a Fry word. */
export const getFryList = (word) => {
  const rank = getFryRank(word)
  return rank ? Math.ceil(rank / 100) : null
}

/** Words in a list (1–10). Each list is taught in four groups of 25. */
export const getListWords = (list) => FRY_LISTS[list - 1]?.words || []

export const getGroupWords = (list, group) =>
  getListWords(list).slice((group - 1) * 25, group * 25)

/** The word exactly as written in the list (keeps "I", "English", etc.). */
export const canonicalWord = (word) => {
  const rank = getFryRank(word)
  return rank ? ALL_FRY_WORDS[rank - 1] : null
}
